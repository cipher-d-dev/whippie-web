// ─── Main page ────────────────────────────────────────────────────────────────

const TEMPLATES: Record<DocType, (props: { internId: string }) => React.ReactNode> = {
  ACCEPTANCE_LETTER:     (p) => <AcceptanceLetterTemplate     {...p} />,
  INTERN_RECORD:         (p) => <InternRecordTemplate         {...p} />,
  COMPLETION_CERTIFICATE:(p) => <CompletionCertificateTemplate {...p} />,
};

export default function DocumentsGeneratePage() {
  const [selectedIntern, setSelectedIntern] = useState("");
  const [selectedDoc,    setSelectedDoc]    = useState<DocType | "">("");
  const [previewing,     setPreviewing]     = useState(false);

  const { data } = useInterns({ limit: 100 });
  const interns  = data?.data ?? [];

  const docCfg = selectedDoc ? DOC_CONFIG[selectedDoc] : null;

  const handlePrint = () => window.print();

  return (
    <>
      {/* Print styles */}
      <style>{`
        @media print {
          body > * { display: none !important; }
          .print-area { display: block !important; }
          .no-print { display: none !important; }
        }
      `}</style>

      <div className="space-y-6 no-print">
        {/* Header */}
        <div>
          <h2 className="text-xl font-semibold">Document Generation</h2>
          <p className="mt-0.5 text-sm text-muted-foreground">
            Generate and print official documents for interns.
          </p>
        </div>

        {/* Global placeholder warning */}
        <div className="flex items-start gap-3 rounded-lg border border-amber-300 bg-amber-50/60 px-4 py-3 dark:bg-amber-950/20">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-amber-600" />
          <div className="text-sm text-amber-700 dark:text-amber-400">
            <p className="font-medium">Templates pending DAAR Communications approval</p>
            <p className="mt-0.5 text-xs">
              The <strong>Intern Record</strong> printout is ready. The Acceptance Letter and Completion Certificate contain placeholder content — do not use for official purposes until approved wording is provided.
            </p>
          </div>
        </div>

        {/* Document type cards */}
        <div className="grid gap-4 sm:grid-cols-3">
          {(Object.entries(DOC_CONFIG) as [DocType, typeof DOC_CONFIG[DocType]][]).map(([type, cfg]) => (
            <Card
              key={type}
              className={`cursor-pointer transition-all hover:shadow-md ${
                selectedDoc === type ? "border-primary ring-1 ring-primary" : ""
              }`}
              onClick={() => { setSelectedDoc(type); setPreviewing(false); }}
            >
              <CardHeader className="pb-2">
                <div className="flex items-start justify-between">
                  <FileText className="h-5 w-5 text-muted-foreground" />
                  <Badge variant={cfg.ready ? "default" : "outline"} className="text-[10px]">
                    {cfg.ready ? "Ready" : "Placeholder"}
                  </Badge>
                </div>
                <CardTitle className="text-sm">{cfg.label}</CardTitle>
              </CardHeader>
              <CardContent>
                <p className="text-xs text-muted-foreground">{cfg.description}</p>
              </CardContent>
            </Card>
          ))}
        </div>

        {/* Intern picker + generate */}
        {selectedDoc && (
          <Card>
            <CardHeader className="pb-3">
              <CardTitle className="text-sm font-medium text-muted-foreground uppercase tracking-wide">
                Generate — {docCfg?.label}
              </CardTitle>
            </CardHeader>
            <CardContent className="space-y-4">
              <div className="space-y-1.5">
                <label className="text-sm font-medium">Select intern</label>
                <Select value={selectedIntern} onValueChange={setSelectedIntern}>
                  <SelectTrigger>
                    <SelectValue placeholder="Choose an intern" />
                  </SelectTrigger>
                  <SelectContent>
                    {interns.map((i) => (
                      <SelectItem key={i._id} value={i._id}>
                        {i.firstName} {i.lastName} · {i.institution}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
              </div>
              <div className="flex gap-3">
                <Button
                  variant="outline"
                  disabled={!selectedIntern}
                  onClick={() => setPreviewing(true)}
                >
                  <ChevronDown className="mr-2 h-4 w-4" />
                  Preview
                </Button>
                <Button
                  disabled={!selectedIntern || !previewing}
                  onClick={handlePrint}
                >
                  <Printer className="mr-2 h-4 w-4" />
                  Print / Save PDF
                </Button>
              </div>
            </CardContent>
          </Card>
        )}
      </div>

      {/* Preview */}
      {previewing && selectedIntern && selectedDoc && (
        <div className="mt-6 no-print">
          {TEMPLATES[selectedDoc]({ internId: selectedIntern })}
        </div>
      )}
    </>
  );
}
