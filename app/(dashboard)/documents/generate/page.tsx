// ─── Document types ───────────────────────────────────────────────────────────

type DocType =
  | "ACCEPTANCE_LETTER"
  | "INTERN_RECORD"
  | "COMPLETION_CERTIFICATE";

const DOC_CONFIG: Record<DocType, { label: string; description: string; ready: boolean }> = {
  ACCEPTANCE_LETTER:    { label: "Acceptance Letter",     description: "Official letter confirming the intern's placement at DAAR Communications.", ready: false },
  INTERN_RECORD:        { label: "Intern Record",         description: "Full profile printout — personal, academic, and internship details.",        ready: true  },
  COMPLETION_CERTIFICATE: { label: "Completion Certificate", description: "Certificate of internship completion for the intern.",                    ready: false },
};

// ─── Template: Intern Record (ready — uses real data) ─────────────────────────

function InternRecordTemplate({ internId }: { internId: string }) {
  const { data } = useIntern(internId);
  const intern = data?.data?.intern;
  if (!intern) return null;

  const fmt = (iso?: string) => iso
    ? new Date(iso).toLocaleDateString("en-GB", { day: "2-digit", month: "long", year: "numeric" })
    : "—";

  return (
    <div className="print-area space-y-6 rounded-lg border bg-white p-8 text-sm text-gray-900 shadow-sm">
      {/* Header */}
      <div className="flex items-start justify-between border-b pb-4">
        <div>
          {/* TODO: Replace with official DAAR Communications logo */}
          <p className="text-lg font-bold">DAAR Communications Plc</p>
          <p className="text-xs text-gray-500">AIT · Raypower · Faaji</p>
        </div>
        <div className="text-right text-xs text-gray-500">
          <p>Intern Record</p>
          <p>Generated: {fmt(new Date().toISOString())}</p>
        </div>
      </div>

      {/* Name */}
      <div>
        <p className="text-xl font-bold">{intern.firstName} {intern.lastName}</p>
        <p className="text-gray-500">{intern.internshipType === "NYSC_IT" ? "NYSC IT" : "Internship"}</p>
      </div>

      {/* Grid */}
      <div className="grid grid-cols-2 gap-x-8 gap-y-3">
        {[
          ["Institution",  intern.institution],
          ["Course",       intern.course],
          ["Level",        intern.level ?? "—"],
          ["Phone",        intern.phone ?? "—"],
          ["Status",       intern.status],
          ["Department",   intern.department?.name ?? "—"],
          ["Supervisor",   intern.supervisor && typeof intern.supervisor !== "string"
            ? `${intern.supervisor.firstName} ${intern.supervisor.lastName}` : "—"],
          ["Start date",   fmt(intern.startDate)],
          ["End date",     fmt(intern.endDate)],
        ].map(([label, value]) => (
          <div key={label}>
            <p className="text-[10px] uppercase tracking-wide text-gray-400">{label}</p>
            <p className="font-medium">{value}</p>
          </div>
        ))}
      </div>

      {/* Footer */}
      <div className="border-t pt-4 text-xs text-gray-400">
        {/* TODO: Replace with official DAAR Communications footer / address */}
        <p>DAAR Communications Plc — [TODO: Official address]</p>
        <p>This document was generated by the Whippe intern management system.</p>
      </div>
    </div>
  );
}

